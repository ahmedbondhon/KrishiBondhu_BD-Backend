"""
api/v1/notifications.py
========================
HTTP route handlers for user notifications.

Routes:
  GET  /api/v1/notifications           → List user notifications (paginated)
  POST /api/v1/notifications/{id}/read → Mark a notification as read
  POST /api/v1/notifications/read-all  → Mark all notifications as read

Notification types generated by the system:
  - 'expert_review_completed' : When an expert submits their review
  - 'case_status_changed'     : When a case moves to a new status
  - 'advisory_updated'        : When an expert updates a previously sent advisory

Notifications are stored in system.notifications (see migration 006).
In a production system these would also be pushed via SMS (Twilio/BulkSMS)
or Firebase Cloud Messaging for mobile push — that is out of scope for MVP.
"""

from datetime import datetime, timezone
from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy import func, select, update
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.dependencies import get_current_user, get_db
from app.core.responses import success_response
from app.models.auth import User
from app.models.system import Notification

router = APIRouter(prefix="/notifications", tags=["Notifications"])


@router.get("", summary="List notifications for the current user")
async def list_notifications(
    unread_only: bool = Query(False, description="If true, return only unread notifications"),
    limit: int = Query(20, ge=1, le=100, description="Max notifications to return"),
    offset: int = Query(0, ge=0, description="Pagination offset"),
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """
    Returns the current user's notifications, most recent first.

    Common notification types:
      - `expert_review_completed` — An expert has submitted their review
      - `case_status_changed`     — Your diagnosis case status was updated
      - `advisory_updated`        — Your advisory was revised by an expert
    """
    query = (
        select(Notification)
        .where(Notification.user_id == current_user.id)
    )

    if unread_only:
        query = query.where(Notification.is_read == False)

    query = query.order_by(Notification.created_at.desc()).limit(limit).offset(offset)

    result = await db.execute(query)
    notifications = result.scalars().all()

    # Count total unread
    unread_count = await db.scalar(
        select(func.count()).select_from(Notification).where(
            Notification.user_id == current_user.id,
            Notification.is_read == False,
        )
    ) or 0

    return success_response(
        data={
            "notifications": [
                {
                    "id": str(n.id),
                    "type": n.notification_type,
                    "title_bn": n.title_bn,
                    "body_bn": n.body_bn,
                    "is_read": n.is_read,
                    "read_at": n.read_at.isoformat() if n.read_at else None,
                    "entity_type": n.entity_type,
                    "entity_id": str(n.entity_id) if n.entity_id else None,
                    "created_at": n.created_at.isoformat() if n.created_at else None,
                }
                for n in notifications
            ],
            "unread_count": unread_count,
        },
        message=f"{len(notifications)}টি বিজ্ঞপ্তি পাওয়া গেছে।",
    )


@router.post("/{notification_id}/read", summary="Mark a single notification as read")
async def mark_notification_read(
    notification_id: UUID,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """Mark a single notification as read."""
    result = await db.execute(
        select(Notification).where(
            Notification.id == notification_id,
            Notification.user_id == current_user.id,
        )
    )
    notification = result.scalar_one_or_none()
    if not notification:
        raise HTTPException(
            status_code=404,
            detail={"code": "NOTIFICATION_NOT_FOUND", "message_bn": "বিজ্ঞপ্তিটি পাওয়া যায়নি।"},
        )

    now = datetime.now(timezone.utc)
    notification.is_read = True
    notification.read_at = now
    await db.flush()

    return success_response(
        data={
            "notification_id": str(notification.id),
            "is_read": True,
            "read_at": now.isoformat(),
        },
        message="বিজ্ঞপ্তি পঠিত হিসেবে চিহ্নিত হয়েছে।",
    )


@router.post("/read-all", summary="Mark all notifications as read")
async def mark_all_read(
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """Mark all of the current user's unread notifications as read at once."""
    now = datetime.now(timezone.utc)
    result = await db.execute(
        update(Notification)
        .where(
            Notification.user_id == current_user.id,
            Notification.is_read == False,
        )
        .values(is_read=True, read_at=now)
    )
    await db.flush()

    return success_response(
        data={
            "marked_read": True,
            "updated_count": result.rowcount,
            "read_at": now.isoformat(),
        },
        message="সব বিজ্ঞপ্তি পঠিত হিসেবে চিহ্নিত হয়েছে।",
    )
