"""
models/system.py
================
SQLAlchemy ORM models for the `system` schema.

Tables mapped here:
  - system.files         → SystemFile   (uploaded file metadata)
  - system.audit_logs    → AuditLog     (immutable audit trail)
  - system.notifications → Notification (user-facing notification messages)

SystemFile tracks every file uploaded to object storage (Supabase/S3).
AuditLog records important actions for compliance and debugging.
Notification stores in-app messages that alert users to case status changes.
"""

import uuid
from datetime import datetime
from typing import Any, Dict, Optional

from sqlalchemy import BigInteger, Boolean, DateTime, ForeignKey, String, Text
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base, TimestampMixin, UUIDPrimaryKeyMixin


class SystemFile(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """
    system.files — Metadata record for every file stored in object storage.

    When a farmer uploads an image, two steps occur:
      1. Backend generates a signed URL → farmer uploads directly to storage.
      2. Farmer calls /files/confirm-upload → this record is created.

    The `storage_path` is the path inside the bucket (not a full URL).
    The `public_url` is only set for public files (avatars etc.).
    Private files (crop images) use signed URLs generated on demand.
    """
    __tablename__ = "files"
    __table_args__ = {"schema": "system"}

    uploaded_by: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True), ForeignKey("auth.users.id", ondelete="SET NULL"))
    original_name: Mapped[str] = mapped_column(String(255), nullable=False)
    storage_path: Mapped[str] = mapped_column(Text, nullable=False)
    bucket_name: Mapped[str] = mapped_column(String(100), default="krishibondhu-uploads", nullable=False)
    provider: Mapped[str] = mapped_column(String(50), default="supabase", nullable=False)
    mime_type: Mapped[str] = mapped_column(String(100), nullable=False)
    file_size_bytes: Mapped[int] = mapped_column(BigInteger, nullable=False)
    checksum: Mapped[Optional[str]] = mapped_column(String(64))
    public_url: Mapped[Optional[str]] = mapped_column(Text)

    # What entity this file belongs to (e.g., 'diagnosis_case', 'user_avatar')
    entity_type: Mapped[Optional[str]] = mapped_column(String(50))
    entity_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True))

    is_processed: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    is_deleted: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    deleted_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True))


# Compatibility alias
File = SystemFile



class AuditLog(Base, UUIDPrimaryKeyMixin):
    """
    system.audit_logs — Append-only log of important system actions.

    Written by services whenever sensitive operations occur:
      - USER_LOGIN, USER_LOGOUT
      - DIAGNOSIS_SUBMITTED, AI_PREDICTION_MADE
      - EXPERT_REVIEW_SUBMITTED, ADVISORY_PUBLISHED
      - USER_ROLE_CHANGED, USER_DELETED

    `old_data` and `new_data` are JSONB snapshots of the entity before/after change.
    This table is NEVER updated — only INSERTs are allowed.
    """
    __tablename__ = "audit_logs"
    __table_args__ = {"schema": "system"}

    user_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True), ForeignKey("auth.users.id", ondelete="SET NULL"))
    action: Mapped[str] = mapped_column(String(100), nullable=False)
    entity_name: Mapped[str] = mapped_column(String(100), nullable=False)
    entity_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True))
    old_data: Mapped[Optional[Dict]] = mapped_column(JSONB)
    new_data: Mapped[Optional[Dict]] = mapped_column(JSONB)
    ip_address: Mapped[Optional[str]] = mapped_column(String(45))
    user_agent: Mapped[Optional[str]] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)


class Notification(Base, UUIDPrimaryKeyMixin):
    """
    system.notifications — In-app notification messages for users.

    Generated by the system when important events occur, e.g.:
      - An expert finishes reviewing a farmer's case.
      - A diagnosis case status changes.
      - An advisory is updated after expert correction.

    Notifications are delivered via:
      - In-app (this table, polled by GET /api/v1/notifications)
      - SMS (via BulkSMS/Bangladesh telco — future implementation)
      - Push notifications (FCM — future implementation)
    """
    __tablename__ = "notifications"
    __table_args__ = {"schema": "system"}

    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("auth.users.id", ondelete="CASCADE"), nullable=False
    )
    notification_type: Mapped[str] = mapped_column(
        String(100), nullable=False,
        comment="e.g. expert_review_completed | case_status_changed | advisory_updated"
    )
    title_bn: Mapped[str] = mapped_column(String(255), nullable=False)
    body_bn: Mapped[Optional[str]] = mapped_column(Text)

    # Which entity this notification is about (e.g., a diagnosis case)
    entity_type: Mapped[Optional[str]] = mapped_column(String(50))
    entity_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True))

    is_read: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    read_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)

